import { mkdirSync, writeFileSync } from 'node:fs';
import { expect, it } from 'vitest';
import { createGenerator, weightedPieceSource } from '../../src/application/piece-source/piece-source';
import { GameSession, startSession } from '../../src/application/session/session';
import type { SessionState } from '../../src/domain/models/types';
import { CLASSIC } from '../domain/helpers';
import recorded from './fixtures/recorded-seed-2026.json';

const tray = (s: SessionState) => s.tray.map((t) => (t ? `#${t.instanceId} ${t.shapeId}` : '—')).join(' | ');
const grid = (s: SessionState) =>
  Array.from({ length: s.board.rows }, (_, y) =>
    s.board.cells.slice(y * s.board.columns, (y + 1) * s.board.columns).map((c) => (c ? '■' : '·')).join(' '),
  ).join('\n');

it('writes a human-readable full-run trace (T12 review evidence)', () => {
  const rules = { config: CLASSIC, gameplayHash: 'review', source: weightedPieceSource };
  const session = new GameSession(rules, startSession(rules, 'review', createGenerator(recorded.seed)));
  const out = [
    `# Sample trace: seed ${recorded.seed}, classic_proposed_v1`,
    '',
    'Generated by `tests/property/sample-trace.test.ts` from the recorded T11 command list. ■ = occupied.',
    '',
    `Start: score 0, revision 0, tray: ${tray(session.state)}`,
  ];
  for (const c of recorded.commands) {
    const before = session.state;
    const slot = before.tray[c.slot]!;
    const r = session.place({
      type: 'PlacePiece',
      sessionId: before.sessionId,
      expectedRevision: before.revision,
      instanceId: slot.instanceId,
      anchor: [c.anchor[0]!, c.anchor[1]!],
    });
    if (!r.accepted) throw new Error(r.reason);
    const lines = [...r.completedRows.map((y) => `row ${y}`), ...r.completedColumns.map((x) => `col ${x}`)];
    out.push(
      '',
      `## Move ${r.moveId}: #${slot.instanceId} ${slot.shapeId} at (${c.anchor.join(',')})`,
      '',
      `Placed ${r.placed.length}, lines ${lines.length ? lines.join(', ') : 'none'}, cleared ${r.cleared.length} cells, ` +
        `delta +${r.scoreDelta}, score ${r.state.score}, status ${r.status}` +
        (r.dealt.length ? `. Refill: ${tray(r.state)}` : `. Tray: ${tray(r.state)}`),
      '',
      '```',
      grid(r.state),
      '```',
    );
  }
  expect(session.state.score).toBe(recorded.expected.score);
  expect(session.state.status).toBe('game_over');
  out.push('', `Game over after ${session.state.revision} moves with score ${session.state.score}: no tray shape has a legal anchor.`, '');
  mkdirSync('docs/evidence/t12', { recursive: true });
  writeFileSync('docs/evidence/t12/sample-trace.md', out.join('\n'));
});
